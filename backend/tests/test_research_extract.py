def test_sections_are_found_and_labelled(paper):
    kinds = [s.kind for s in paper.sections]
    assert kinds.count("abstract") == 1
    assert kinds.count("references") == 1
    assert kinds.count("body") >= 5
    titles = [s.title for s in paper.sections]
    assert "I. INTRODUCTION" in titles
    assert "VI. CONCLUSION" in titles


def test_abstract_run_on_label_is_split_off(paper):
    abstract = next(s for s in paper.sections if s.kind == "abstract")
    assert abstract.title.lower().startswith("abstract")
    assert abstract.text.startswith("Long-form reading has declined")
    assert "Abstract-" not in abstract.text


def test_references_are_one_section_not_many(paper):
    """Reference entries open with words that are also section names
    ("Approach.", "design,"), which used to cut the list into pieces."""
    references = [s for s in paper.sections if s.kind == "references"]
    assert len(references) == 1
    assert "Paivio" in references[0].text
    assert "IEEE Trans. Learn. Technol." in references[0].text


def test_references_are_outside_the_reading_flow(paper):
    readable = " ".join(s.text for s in paper.sections if s.kind in R.READABLE_KINDS)
    assert "Paivio, Mental Representations" not in readable
    assert paper.readable_words < sum(word_count(s.text) for s in paper.sections)


def test_the_title_block_is_not_a_section_to_read(paper):
    """The title, byline and venue are the metadata. Keeping them as a section
    too put an untitled "Title page" entry at the top of every document, with
    nothing in it the panel beside it did not already say."""
    assert not any(s.kind == "front_matter" for s in paper.sections)
    assert paper.sections[0].kind == "abstract"


def test_a_byline_is_never_mistaken_for_a_heading(paper):
    """A byline reading "A. Reader, B. Writer" looks exactly like an IEEE
    subsection heading, so everything above the first real heading is held out
    by position rather than by what it says."""
    assert not any(s.title.startswith("A. Reader") for s in paper.sections)


def test_every_section_kind_is_one_we_store(paper):
    assert {s.kind for s in paper.sections} <= set(R.RESEARCH_SECTION_KINDS)


