def test_two_column_pages_are_detected_as_two_columns():
    pages = pdf_layout.read_pages(INTERLEAVED.read_bytes())
    body_pages = [p for p in pages if len(p.lines) > 40]
    assert body_pages, "expected several pages of body text"
    assert all(p.column_count == 2 for p in body_pages)


def test_single_column_pages_report_no_columns():
    pages = pdf_layout.read_pages(TEXTBOOK.read_bytes())
    assert all(page.column_count == 1 for page in pages)


def test_full_width_lines_are_not_cut_at_the_gutter():
    """The title spans both columns. Splitting it there was a real bug: the
    character sitting astride the boundary read as a gutter-sized gap."""
    pages = pdf_layout.read_pages(INTERLEAVED.read_bytes())
    titles = [ln.text for ln in pages[0].lines if ln.size >= 14]
    assert "Attention Scaffolding for Sustained Long-Form Reading" in titles


def test_running_header_and_page_numbers_are_removed(paper):
    body = "\n".join(s.text for s in paper.sections)
    assert "IEEE TRANSACTIONS ON LEARNING TECHNOLOGIES" not in body
    # The folio is a bare number on its own line; none should survive.
    assert not [line for line in body.split("\n") if line.strip().isdigit()]


def test_repeated_edge_lines_tolerate_a_changing_page_number():
    pages = pdf_layout.read_pages(INTERLEAVED.read_bytes())
    repeated = pdf_layout.repeated_edge_lines(pages)
    assert any("IEEE TRANSACTIONS" in line for line in repeated)


