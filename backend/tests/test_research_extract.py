"""Layout-aware extraction of research PDFs.

The fixtures are generated by tests/fixtures/make_research_fixtures.py and
committed, so these tests need no network and no PDF tooling beyond the
dependency itself. The two-column paper exists in two versions - one whose
producer ships text row by row, one column by column - because the whole point
of this path is that the result should not depend on which you have.
"""

from pathlib import Path

import pytest

from app.services import pdf_layout, research_extract as R
from app.services.extract import ExtractionError
from app.services.segmentation import word_count

FIXTURES = Path(__file__).parent / "fixtures" / "research"
UPLOADS = Path(__file__).parent / "fixtures" / "uploads"

INTERLEAVED = FIXTURES / "twocol_interleaved.pdf"
COLUMN_MAJOR = FIXTURES / "twocol_columnmajor.pdf"
TEXTBOOK = FIXTURES / "textbook_outline.pdf"
SCANNED = UPLOADS / "scanned.pdf"


@pytest.fixture(scope="module")
def paper():
    return R.extract_research_pdf(INTERLEAVED.read_bytes())


@pytest.fixture(scope="module")
def textbook():
    return R.extract_research_pdf(TEXTBOOK.read_bytes())


