def _line(text, size=9.5):
    from app.services.pdf_layout import Line

    return Line(text=text, x0=0, x1=100, top=0, bottom=10, size=size)


@pytest.mark.parametrize("text", ["evaluation", "results", "method", "discussion"])
def test_a_lower_case_word_alone_on_a_line_is_not_a_heading(text):
    """A section name in lower case is prose that wrapped, not a heading. This
    is what put entries like "evaluation" in the section list."""
    assert R.looks_like_heading(_line(text), 9.5) is False


@pytest.mark.parametrize(
    "text",
    ["IV. EVALUATION", "4. Evaluation", "Evaluation", "RESULTS", "V. DISCUSSION", "4.2 Datasets"],
)
def test_a_real_heading_is_still_found(text):
    assert R.looks_like_heading(_line(text), 9.5) is True


def test_every_section_title_looks_like_a_heading(paper):
    """Nothing in the section list should be a stray word or a sentence."""
    for section in paper.sections:
        if not section.title:
            continue
        assert len(section.title) <= R.MAX_HEADING_CHARS
        assert not section.title.islower()


