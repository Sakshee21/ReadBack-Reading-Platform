@pytest.mark.parametrize(
    "broken,repaired",
    [
        ("T HE Internet", "THE Internet"),
        ("T he quick brown fox", "The quick brown fox"),
        ("I NTRODUCTION", "INTRODUCTION"),
        ("A BSTRACT", "ABSTRACT"),
        ("R ELATED W ORK", "RELATED W ORK"),  # only the leading cap is repaired
    ],
)
def test_a_split_leading_capital_is_repaired(broken, repaired):
    assert R.repair_split_capitals(broken) == repaired


@pytest.mark.parametrize(
    "text",
    [
        "A Study of Honeypots",  # "A" is a word
        "A MITRE dataset",  # an acronym after the article
        "I have seen this before",
        "THE INTERNET",  # nothing split
        "U. S. Army doctrine",  # initials keep their stops
        "A. Reader, B. Writer",  # a byline, not a drop cap
        "vitamin C and iron",  # mid-sentence, never touched
    ],
)
def test_ordinary_text_is_left_alone(text):
    assert R.repair_split_capitals(text) == text


