# ---------------------------------------------------------------------------
# the paper that caused all of this, end to end
#
# messy_paper.pdf has the three shapes that made the extractor invent
# metadata: no byline (an affiliation stands where the authors would be), no
# date anywhere, and a heading whose first letter is set as its own run.
# ---------------------------------------------------------------------------

MESSY = FIXTURES / "messy_paper.pdf"


@pytest.fixture(scope="module")
def messy():
    if not MESSY.exists():
        pytest.skip("run tests/fixtures/make_research_fixtures.py")
    return R.extract_research_pdf(MESSY.read_bytes())


def test_no_author_is_found_rather_than_a_sentence(messy):
    assert messy.metadata.authors == ""
    assert "Honeypot and labeled" not in messy.metadata.authors
    assert "could not be read" in " ".join(
        w for w in messy.warnings if "authors" in w
    )


def test_an_affiliation_is_not_an_author(messy):
    assert "Department" not in messy.metadata.authors
    assert "University" not in messy.metadata.authors


def test_a_producer_name_in_the_author_field_is_ignored(messy):
    """This fixture carries /Author = "Microsoft Word"."""
    assert messy.metadata.authors == ""


def test_no_year_is_found_rather_than_a_wrong_one(messy):
    assert messy.metadata.year is None
    assert "year" not in messy.metadata.unverified  # nothing to be unsure about


def test_the_title_is_still_read(messy):
    """Refusing to guess the author must not cost us the fields that are there."""
    assert messy.metadata.title == "Detecting Intrusions with Honeypots"


def test_a_drop_cap_heading_is_repaired(messy):
    titles = [s.title for s in messy.sections]
    assert "THE Internet of Things" in titles
    assert not any(t.startswith("T HE") for t in titles)


def test_the_messy_paper_has_no_junk_sections(messy):
    kinds = [s.kind for s in messy.sections]
    assert "front_matter" not in kinds  # no "Title page" entry
    for section in messy.sections:
        assert not section.title.islower()
    # The running head repeats, so it is furniture and not a section.
    assert not any("DETECTING INTRUSIONS" in s.title for s in messy.sections)


def test_the_body_text_survives_all_of_this(messy):
    body = " ".join(s.text for s in messy.sections if s.kind == "body")
    assert "Traffic was captured over six months" in body
    assert "Honeypot and labeled according to" in body  # still readable as prose
