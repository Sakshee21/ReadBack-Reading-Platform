def test_columns_are_read_down_not_across(paper):
    """The sentence that the book path splices into its neighbour."""
    body = " ".join(s.text for s in paper.sections if s.kind == "body")
    assert (
        "The activation energy required to begin a reading session is "
        "disproportionately high when compared with low-effort alternatives."
    ) in body


def test_hyphenated_line_break_is_rejoined(paper):
    body = " ".join(s.text for s in paper.sections if s.kind == "body")
    assert "disproportionately" in body
    assert "dispropor tionately" not in body
    assert "dispropor-" not in body


def test_result_does_not_depend_on_content_stream_order():
    """A row-interleaved and a column-major PDF of the same paper must come out
    the same. This is the property the whole layout path exists for."""
    interleaved = R.extract_research_pdf(INTERLEAVED.read_bytes())
    column_major = R.extract_research_pdf(COLUMN_MAJOR.read_bytes())
    assert [(s.kind, s.title) for s in interleaved.sections] == [
        (s.kind, s.title) for s in column_major.sections
    ]
    assert [s.text for s in interleaved.sections] == [s.text for s in column_major.sections]


