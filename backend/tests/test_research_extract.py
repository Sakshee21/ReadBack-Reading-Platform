# ---------------------------------------------------------------------------
# metadata that must never be guessed
#
# From a real failure: a paper produced the citation
#   (Honeypot et al., n.d., T HE Internet)
# with the author field holding a sentence out of the body of the paper, no
# year, and a heading mangled by a drop cap. Each of these covers one part of
# that.
# ---------------------------------------------------------------------------

SENTENCE_FROM_A_PAPER = (
    "Honeypot and labeled according to Enterprise Tactics of MITRE ATT&CK "
    "to ensure dataset credibility."
)


@pytest.mark.parametrize(
    "line",
    [
        SENTENCE_FROM_A_PAPER,
        "The dataset was collected from a honeypot and labelled by hand",
        "We propose a method for detecting intrusions",
        "This paper is organised as follows",
        "Department of Computer Science, University of Somewhere",
        "alice@example.edu, bob@example.edu",
        "Received 3 March 2021; accepted 14 June 2021",
        "1 Introduction",
        "Abstract",
        "Keywords: honeypot, intrusion detection",
        "Smith",  # one bare surname is a label, not a byline
        "",
    ],
)
def test_a_byline_is_refused_when_it_is_not_names(line):
    assert R.looks_like_byline(line) is False


@pytest.mark.parametrize(
    "line",
    [
        "A. Reader, B. Writer, and C. Editor",
        "Alice Reader, Bob Writer",
        "Reader, Alice; Writer, Bob",
        "Jane Doe",
        "J. R. R. Tolkien",
        "Ludwig van Beethoven, Anna de la Cruz",
        "Alice Reader and Bob Writer",
    ],
)
def test_a_real_byline_is_accepted(line):
    assert R.looks_like_byline(line) is True


def test_the_sentence_that_caused_the_bug_is_not_an_author(paper):
    """The whole point: a blank author field is a visible gap, a wrong one is
    not."""
    assert R.looks_like_byline(SENTENCE_FROM_A_PAPER) is False
    assert SENTENCE_FROM_A_PAPER not in paper.metadata.authors


def test_an_embedded_author_field_still_has_to_look_like_a_byline():
    """Producers write all sorts into /Author - a username, a department, the
    name of the typesetter."""
    assert R.looks_like_byline("sakshee") is False
    assert R.looks_like_byline("Department of Computer Science") is False


@pytest.mark.parametrize(
    "value", ["Microsoft Word", "Adobe Acrobat", "pdfTeX", "Administrator", "Unknown"]
)
def test_a_producer_name_is_not_an_author(value):
    """"Microsoft Word" has exactly the shape of "Jane Doe", so no rule about
    shape can tell them apart. It takes a list."""
    assert R._is_software_name(value) is True


def test_a_real_name_is_not_mistaken_for_software():
    assert R._is_software_name("Jane Doe") is False
    assert R._is_software_name("B. Writer") is False  # "Writer" is a surname


